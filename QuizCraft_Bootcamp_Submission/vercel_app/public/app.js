// QuizCraft frontend: JavaScript controls what the user sees and clicks.
// Python/FastAPI (index.py) handles AI generation and protects the Gemini key.
const $ = (id) => document.getElementById(id);
const state = { quiz: null, tab: 'review', answers: {}, checked: false, busy: false };
const LETTERS = ['A', 'B', 'C', 'D'];
let toastTimer = null;

function toast(message, error = false) {
  const box = $('toast');
  box.textContent = message;
  box.className = `toast visible${error ? ' error' : ''}`;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { box.className = 'toast'; }, 4300);
}

async function api(path, options = {}) {
  const response = await fetch(path, options);
  if (!response.ok) {
    let message = `Server error ${response.status}.`;
    try {
      const body = await response.json();
      message = typeof body.detail === 'string' ? body.detail :
        (Array.isArray(body.detail) ? 'Check your lesson text and question settings.' : message);
    } catch (_) { /* Keep original error text. */ }
    throw new Error(message);
  }
  return response.json();
}

// For untrusted lesson/AI text, ALWAYS use .textContent or .value, not .innerHTML.
function element(tag, className = '', text = '') {
  const node = document.createElement(tag);
  if (className) node.className = className;
  node.textContent = text;
  return node;
}
function add(parent, tag, className, text) {
  const child = element(tag, className, text);
  parent.appendChild(child);
  return child;
}
function textField(label, value, onEdit, multiline = false) {
  const wrap = element('div');
  add(wrap, 'label', 'small-label', label);
  const field = document.createElement(multiline ? 'textarea' : 'input');
  field.className = 'editor-input' + (multiline ? ' editor-textarea' : '');
  field.value = value;
  if (!multiline) field.type = 'text';
  field.addEventListener('input', () => onEdit(field.value));
  wrap.appendChild(field);
  return wrap;
}
function quizConfig() {
  return {
    lesson: $('lesson').value.trim(),
    total: Number($('question-count').value),
    mode: $('question-types').value,
    difficulty: $('difficulty').value,
    language: $('language').value,
  };
}
function updateCounter() { $('lesson-count').textContent = String($('lesson').value.trim().length); }
function setBusy(busy) {
  state.busy = busy;
  $('generate').disabled = busy;
  $('demo').disabled = busy;
  $('generate').textContent = busy ? '✦ Generating questions…' : '✧ Generate with Gemini';
}

async function loadSample() {
  try {
    const result = await api('/api/sample');
    $('lesson').value = result.lesson;
    updateCounter();
    toast('Example lesson loaded. Choose your settings and generate.');
  } catch (error) { toast(error.message, true); }
}
async function generate() {
  const payload = quizConfig();
  if (payload.lesson.length < 80 || payload.lesson.length > 20000) {
    toast('Please enter lesson notes between 80 and 20,000 characters.', true); return;
  }
  setBusy(true);
  try {
    const quiz = await api('/api/generate', {
      method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Demo-Access': $('demo-code').value }, body: JSON.stringify(payload)
    });
    setQuiz(quiz);
    toast('Gemini generated your quiz. Now review and approve each question.');
  } catch (error) { toast(error.message, true); }
  finally { setBusy(false); }
}
async function loadDemo() {
  setBusy(true);
  try {
    const quiz = await api('/api/demo');
    setQuiz(quiz);
    toast('Prewritten demo loaded — these questions were not generated by Gemini.');
  } catch (error) { toast(error.message, true); }
  finally { setBusy(false); }
}
function setQuiz(quiz) {
  state.quiz = quiz;
  state.answers = {};
  state.checked = false;
  $('empty-state').hidden = true;
  $('quiz-workspace').hidden = false;
  $('source-label').textContent = quiz.source === 'demo' ? 'OFFLINE DEMO' : 'GENERATED BY GEMINI';
  $('source-label').className = 'source-tag ' + (quiz.source === 'demo' ? 'demo' : 'generated');
  $('quiz-title').textContent = quiz.title;
  updateMetrics();
  setTab('review');
}
function approvedQuestions() {
  if (!state.quiz) return [];
  return state.quiz.questions.map((q, index) => ({ q, index })).filter(x => x.q.approved);
}
function updateMetrics() {
  const qs = state.quiz.questions;
  $('metric-total').textContent = qs.length;
  $('metric-mcq').textContent = qs.filter(q => q.question_type === 'multiple_choice').length;
  $('metric-approved').textContent = qs.filter(q => q.approved).length;
  $('approval-message').textContent = `${approvedQuestions().length} of ${qs.length} approved`;
}
function setTab(tab) {
  state.tab = tab;
  for (const current of ['review', 'student', 'export']) {
    const active = current === tab;
    $(`tab-${current}`).classList.toggle('is-active', active);
    $(`tab-${current}`).setAttribute('aria-selected', active ? 'true' : 'false');
    $(`${current}-view`).hidden = !active;
  }
  if (tab === 'review') renderReview();
  if (tab === 'student') renderStudent();
}
function validateReview(q) {
  if (!q.question.trim() || !q.explanation.trim()) return 'Add question wording and an explanation.';
  if (q.question_type === 'short_answer') {
    return q.suggested_answer.trim() ? '' : 'Add a suggested answer.';
  }
  if (q.options.length !== 4 || q.options.some(x => !x.trim())) return 'All four options are required.';
  if (new Set(q.options.map(x => x.trim().toLowerCase())).size !== 4) return 'The four options must be distinct.';
  if (!LETTERS.includes(q.correct_option)) return 'Choose the correct answer letter.';
  return '';
}
function invalidateApproval(q, checkbox) {
  if (q.approved) {
    q.approved = false;
    if (checkbox) checkbox.checked = false;
    updateMetrics();
  }
}
function renderReview() {
  const root = $('review-questions');
  root.replaceChildren();
  state.quiz.questions.forEach((q, index) => {
    const card = element('article', 'question-card');
    const head = add(card, 'div', 'qcard-head');
    const group = add(head, 'div');
    add(group, 'span', 'qnum', `Q${String(index + 1).padStart(2, '0')}`);
    add(group, 'span', 'type-chip', q.question_type === 'multiple_choice' ? 'Multiple choice' : 'Short answer');
    add(head, 'span', 'approved-pill', q.approved ? '✓ Approved' : 'Awaiting review');
    const approvalLabel = head.querySelector('.approved-pill');
    const approvalRow = element('div', 'approval-row');
    const toggleLabel = element('label', 'toggle-line');
    const approval = document.createElement('input'); approval.type = 'checkbox'; approval.checked = !!q.approved;
    toggleLabel.appendChild(approval);
    add(toggleLabel, 'span', '', 'Teacher approval');
    approvalRow.appendChild(toggleLabel);
    add(approvalRow, 'span', 'type-chip', 'Manual review required');
    const changed = () => { invalidateApproval(q, approval); approvalLabel.textContent = 'Awaiting review'; };
    card.appendChild(textField('Question', q.question, value => { q.question = value; changed(); }, true));

    if (q.question_type === 'multiple_choice') {
      const optionsGrid = add(card, 'div', 'options-editor');
      q.options.forEach((option, oi) => {
        optionsGrid.appendChild(textField(`Option ${LETTERS[oi]}`, option, value => {
          q.options[oi] = value;
          q.suggested_answer = q.options[LETTERS.indexOf(q.correct_option)];
          changed();
        }));
      });
      const answer = add(card, 'div', 'answer-control');
      const select = document.createElement('select'); select.setAttribute('aria-label', 'Correct option');
      LETTERS.forEach(letter => { const opt = document.createElement('option'); opt.value = letter; opt.textContent = `Answer ${letter}`; select.appendChild(opt); });
      select.value = q.correct_option;
      select.addEventListener('change', () => { q.correct_option = select.value; q.suggested_answer = q.options[LETTERS.indexOf(q.correct_option)]; changed(); });
      answer.appendChild(select);
      add(answer, 'span', '', 'Correct option · selected by the teacher');
    } else {
      card.appendChild(textField('Suggested short answer', q.suggested_answer, value => {
        q.suggested_answer = value; changed();
      }, true));
    }
    card.appendChild(textField('Explanation', q.explanation, value => { q.explanation = value; changed(); }, true));
    const evidence = add(card, 'p', 'evidence', q.source_excerpt ? `Evidence from the original lesson: “${q.source_excerpt}”` : 'No verified source excerpt. Check this answer manually.');
    evidence.title = 'An excerpt is shown only when it matches the original lesson. Editing a question can invalidate its relevance.';
    approval.addEventListener('change', () => {
      if (approval.checked) {
        const message = validateReview(q);
        if (message) { approval.checked = false; toast(`Question ${index + 1}: ${message}`, true); return; }
      }
      q.approved = approval.checked;
      approvalLabel.textContent = q.approved ? '✓ Approved' : 'Awaiting review';
      state.answers = {}; state.checked = false;
      updateMetrics();
    });
    card.appendChild(approvalRow);
    root.appendChild(card);
  });
}
function approveAll() {
  let count = 0;
  state.quiz.questions.forEach(q => { if (!validateReview(q)) { q.approved = true; count++; } });
  updateMetrics(); renderReview();
  toast(`${count} valid questions approved. Review their content before using them.`);
}
function renderStudent() {
  const root = $('student-questions');
  root.replaceChildren();
  const items = approvedQuestions();
  $('student-actions').hidden = !items.length;
  $('score-result').hidden = !state.checked || !items.length;
  if (!items.length) {
    add(root, 'p', 'blank-note', 'No approved questions yet. Open Teacher review, check the content, and approve at least one question.');
    return;
  }
  items.forEach(({ q, index }, position) => {
    const card = add(root, 'article', 'student-card');
    add(card, 'span', 'type-chip', `Question ${position + 1} · ${q.question_type === 'multiple_choice' ? 'Multiple choice' : 'Short answer'}`);
    add(card, 'h4', '', q.question);
    if (q.question_type === 'multiple_choice') {
      q.options.forEach((option, oi) => {
        const label = add(card, 'label', 'answer-choice');
        const radio = document.createElement('input'); radio.type = 'radio'; radio.name = `student-q-${index}`; radio.value = LETTERS[oi];
        radio.checked = state.answers[index] === LETTERS[oi]; radio.disabled = state.checked;
        radio.addEventListener('change', () => { state.answers[index] = LETTERS[oi]; });
        label.appendChild(radio);
        add(label, 'span', '', `${LETTERS[oi]}. ${option}`);
      });
    } else {
      const area = document.createElement('textarea');
      area.className = 'editor-input student-answer';
      area.placeholder = 'Type your answer here…'; area.value = state.answers[index] || '';
      area.disabled = state.checked;
      area.addEventListener('input', () => { state.answers[index] = area.value; });
      card.appendChild(area);
    }
    if (state.checked) {
      const solution = add(card, 'div', 'solution');
      const correct = q.question_type === 'multiple_choice' ? `${q.correct_option}. ${q.suggested_answer}` : q.suggested_answer;
      add(solution, 'strong', '', `Suggested answer: ${correct}`);
      add(solution, 'p', '', q.explanation);
    }
  });
  $('check-answers').textContent = state.checked ? 'Try this quiz again' : 'Check my answers';
  if (state.checked) {
    const mcq = items.filter(({q}) => q.question_type === 'multiple_choice');
    const nCorrect = mcq.filter(({q, index}) => state.answers[index] === q.correct_option).length;
    $('score-result').textContent = `Multiple-choice score: ${nCorrect}/${mcq.length}. ${mcq.length ? Math.round(nCorrect * 100 / mcq.length) + '%' : 'No MCQ to score.'} Written answers are shown for self-assessment and are NOT automatically graded.`;
  }
}
function checkAnswers() {
  if (state.checked) { state.checked = false; state.answers = {}; }
  else { state.checked = true; }
  renderStudent();
}
function safeCell(value) {
  const text = String(value ?? '');
  // Prevent formula injection when a downloaded CSV is opened in Excel.
  return /^[\s]*[=+\-@\t\r]/.test(text) ? `'${text}` : text;
}
function csvEscape(value) { return `"${safeCell(value).replaceAll('"', '""')}"`; }
function selectedExportQuestions() {
  return state.quiz.questions.filter(q => !$('approved-only').checked || q.approved);
}
function download(filename, type, content) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a'); anchor.href = url; anchor.download = filename;
  document.body.appendChild(anchor); anchor.click(); anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
function exportQuiz(format) {
  const questions = selectedExportQuestions();
  if (!questions.length) { toast('No approved questions to export. Approve some or turn off the filter.', true); return; }
  const quiz = { title: state.quiz.title, total_questions: questions.length, source: state.quiz.source, questions };
  if (format === 'json') {
    download('quizcraft_questions.json', 'application/json', JSON.stringify(quiz, null, 2));
  } else {
    const rows = [['number','question_type','question','option_A','option_B','option_C','option_D','correct_option','suggested_answer','explanation','source_excerpt','approved']];
    questions.forEach((q, i) => { rows.push([i+1,q.question_type,q.question,...[0,1,2,3].map(j => q.options[j] || ''),q.correct_option,q.suggested_answer,q.explanation,q.source_excerpt,q.approved?'Yes':'No']); });
    download('quizcraft_questions.csv', 'text/csv;charset=utf-8', '\ufeff' + rows.map(row => row.map(csvEscape).join(',')).join('\r\n'));
  }
  toast(`Downloaded ${questions.length} ${format.toUpperCase()} questions.`);
}
async function checkServer() {
  const label = $('connection-status');
  try {
    const info = await api('/api/health');
    $('code-wrap').hidden = !info.access_code_required;
    label.textContent = info.gemini_configured ? `✓ Gemini ready · ${info.model}` : '⚠ Demo mode · add Gemini key';
    label.className = 'status-pill ' + (info.gemini_configured ? 'ok' : 'warning');
  } catch (_) { label.textContent = '⚠ Backend unavailable'; label.className = 'status-pill warning'; }
}

