$('check-answers').addEventListener('click', checkAnswers);
$('download-json').addEventListener('click', () => exportQuiz('json'));
$('download-csv').addEventListener('click', () => exportQuiz('csv'));
['review','student','export'].forEach(tab => $(`tab-${tab}`).addEventListener('click', () => setTab(tab)));
$('file-upload').addEventListener('change', async event => {
  const file = event.target.files?.[0];
  if (!file) return;
  if (!/\.(txt|md)$/i.test(file.name)) { toast('Choose a .txt or .md file.', true); return; }
  if (file.size > 70000) { toast('File too large. Maximum 70 KB.', true); return; }
  $('lesson').value = await file.text(); updateCounter();
  toast('Lesson file loaded.');
});
checkServer();
